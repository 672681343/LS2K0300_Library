#include "Encoder.h"
namespace Encoder {
    CountPram count = {
        .L = 0,
        .R = 0,
        .L_real = 0,
        .R_real = 0
    };
    //-------------------------------------------------------------------------------------------------------------------
    // 函数简介: 更新编码器
    // 参数说明: 编码器
    // 返回参数: 编码器值
    // 使用示例: Encoder::update()
    // 备注信息: 中断定时调用
    //-------------------------------------------------------------------------------------------------------------------
    void update() {

        count.R = -encoder_get_count(LEFT_DEVICE);
        count.L = encoder_get_count(RIGHT_DEVICE);
    }
    
}